    private void ucitajPodatke() {
        try {
            java.util.Properties p = new java.util.Properties();
            p.load(new java.io.FileInputStream("config/dbconfig.properties"));
            txtUrl.setText(p.getProperty("url"));
            txtUsername.setText(p.getProperty("username"));
            jPasswordField1.setText(p.getProperty("password"));
        } catch (Exception ex) {
            txtUrl.setText("jdbc:mysql://localhost:3306/poslasticarnica?useSSL=false&serverTimezone=UTC"); 
            txtUsername.setText("root");
            jPasswordField1.setText("");
        }
    }
    
