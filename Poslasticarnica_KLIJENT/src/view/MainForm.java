    private void stilizuj() {
        if (jMenuBar1 != null) {
            Stil.meni(jMenuBar1);
        }
        Stil.pozadina(getContentPane());
        pnlHeader.setBackground(Stil.BRAON);

        java.awt.Font fontGlavniNaslov = new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 28);
        java.awt.Font fontDobrodosli = new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 18);

        lblNazivSistema.setForeground(Stil.BELA);
        lblNazivSistema.setFont(fontGlavniNaslov);
        lblDobrodosli.setForeground(Stil.KREM_SVETLA);
        lblDobrodosli.setFont(fontDobrodosli);

        pnlHeader.setBorder(javax.swing.BorderFactory.createEmptyBorder(30, 20, 30, 20));
        pnlHeader.revalidate();
        pnlHeader.repaint();
        this.getContentPane().revalidate();
        this.getContentPane().repaint();
    }
